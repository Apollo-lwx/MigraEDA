"""Render DiffResult to Markdown / HTML / JSON helpers."""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any

from migraeda.models import DiffResult


def render_markdown(diff: DiffResult) -> str:
    lines = [
        f"# MigraEDA Diff Report — **{diff.grade.value}**",
        "",
        diff.summary,
        "",
        "## Checks",
        "",
        "| Check | Grade | Message |",
        "|-------|-------|---------|",
    ]
    for c in diff.checks:
        msg = c.message.replace("|", "\\|")
        lines.append(f"| `{c.name}` | **{c.grade.value}** | {msg} |")
    lines.append("")
    if diff.source:
        lines.append("## Source stats")
        lines.append("")
        lines.append("```json")
        lines.append(json.dumps(diff.source.to_dict(), indent=2, ensure_ascii=False))
        lines.append("```")
        lines.append("")
    if diff.target:
        lines.append("## Target stats")
        lines.append("")
        lines.append("```json")
        lines.append(json.dumps(diff.target.to_dict(), indent=2, ensure_ascii=False))
        lines.append("```")
        lines.append("")
    lines.append("---")
    lines.append("*Generated by MigraEDA — verifiable migration, not blind conversion.*")
    lines.append("")
    return "\n".join(lines)


def render_html(diff: DiffResult) -> str:
    color = {"PASS": "#0a7", "WARN": "#c80", "FAIL": "#c00"}[diff.grade.value]
    rows = "".join(
        f"<tr><td><code>{html.escape(c.name)}</code></td>"
        f"<td><strong>{c.grade.value}</strong></td>"
        f"<td>{html.escape(c.message)}</td></tr>"
        for c in diff.checks
    )
    src = html.escape(json.dumps(diff.source.to_dict() if diff.source else {}, indent=2))
    tgt = html.escape(json.dumps(diff.target.to_dict() if diff.target else {}, indent=2))
    return f"""<!DOCTYPE html>
<html lang="zh-CN"><head><meta charset="utf-8"/>
<title>MigraEDA Diff — {diff.grade.value}</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem}}
.badge{{display:inline-block;padding:.2rem .6rem;border-radius:4px;color:#fff;background:{color}}}
table{{border-collapse:collapse;width:100%}} th,td{{border:1px solid #ddd;padding:.4rem .6rem;text-align:left}}
pre{{background:#f6f8fa;padding:1rem;overflow:auto}}
</style></head><body>
<h1>MigraEDA Diff Report <span class="badge">{diff.grade.value}</span></h1>
<p>{html.escape(diff.summary)}</p>
<h2>Checks</h2>
<table><thead><tr><th>Check</th><th>Grade</th><th>Message</th></tr></thead>
<tbody>{rows}</tbody></table>
<h2>Source</h2><pre>{src}</pre>
<h2>Target</h2><pre>{tgt}</pre>
<hr/><p><em>Generated by MigraEDA</em></p>
</body></html>
"""


def write_report(
    diff: DiffResult,
    output: str | Path,
    *,
    fmt: str = "md",
) -> Path:
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "html":
        output.write_text(render_html(diff), encoding="utf-8")
    elif fmt == "json":
        output.write_text(
            json.dumps(diff.to_dict(), indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
    else:
        output.write_text(render_markdown(diff), encoding="utf-8")
    return output


def load_diff_json(path: str | Path) -> DiffResult:
    """Rehydrate a DiffResult from diff.json (for `migraeda report`)."""
    from migraeda.models import DiffCheck, DiffGrade, ProjectStats

    data: dict[str, Any] = json.loads(Path(path).read_text(encoding="utf-8"))
    checks = [
        DiffCheck(
            name=c["name"],
            grade=DiffGrade(c["grade"]),
            message=c["message"],
            source_value=c.get("source_value"),
            target_value=c.get("target_value"),
        )
        for c in data.get("checks") or []
    ]
    src = ProjectStats.from_dict(data["source"]) if data.get("source") else None
    tgt = ProjectStats.from_dict(data["target"]) if data.get("target") else None
    return DiffResult(
        grade=DiffGrade(data["grade"]),
        checks=checks,
        source=src,
        target=tgt,
        summary=str(data.get("summary") or ""),
    )
